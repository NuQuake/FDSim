FUNCTION  IND (I,K)

  IMPLICIT NONE

  INTEGER, INTENT(IN ) :: I,K
  INTEGER              :: IND

  IND = 1 + MOD(ABS(I-1),2) + 2*MOD(ABS(K-1),2)

END FUNCTION  IND
